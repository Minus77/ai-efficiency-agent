def grouped_terms() -> list[dict[str, Any]]:
    """按主题分组的术语，供参考页渲染。"""
    return [
        {
            "group": name,
            "intro": intro,
            "terms": [
                {"key": k, "label": GLOSSARY[k].label, "plain": GLOSSARY[k].plain, "why": GLOSSARY[k].why}
                for k in keys
            ],
        }
        for name, intro, keys in GROUPS
    ]


# ---------------------------------------------------------------------------
# 查询
# ---------------------------------------------------------------------------
_ALIAS_INDEX: dict[str, str] = {}
for _key, _term in GLOSSARY.items():
    _ALIAS_INDEX[_key.lower()] = _key
    _ALIAS_INDEX[_term.label.lower()] = _key
    for _a in _term.aliases:
        _ALIAS_INDEX[_a.lower()] = _key


def lookup(word: str) -> Term | None:
    if not word:
        return None
    return GLOSSARY.get(_ALIAS_INDEX.get(word.strip().lower(), ""))


def explain(word: str) -> dict[str, Any] | None:
    term = lookup(word)
    if term is None:
        return None
    return {"key": term.key, "label": term.label, "plain": term.plain, "why": term.why}


def all_terms() -> list[dict[str, Any]]:
    return [
        {"key": t.key, "label": t.label, "plain": t.plain, "why": t.why}
        for t in GLOSSARY.values()
    ]


